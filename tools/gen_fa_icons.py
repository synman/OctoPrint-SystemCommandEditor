#!/usr/bin/env python3
"""Generate the icon picker's list from Font Awesome Free's metadata.

OctoPrint 1.11 and 2.0 ship Font Awesome Free 6.5.1, so the list comes from that release's icons.yml:

    curl -sSfL -o icons.yml https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@6.5.1/metadata/icons.yml
    python3 tools/gen_fa_icons.py icons.yml

It rewrites octoprint_systemcommandeditor/static/js/systemcommandeditor_icons.js. Each entry is
[name, styles, label, search words], with styles as letters: s solid, r regular, b brands.
"""
import json
import os
import sys

import yaml

STYLE_LETTERS = {"solid": "s", "regular": "r", "brands": "b"}
OUT = os.path.join(os.path.dirname(__file__), "..", "octoprint_systemcommandeditor", "static", "js",
                   "systemcommandeditor_icons.js")


def entries(icons):
    out = []
    for name in sorted(icons):
        icon = icons[name]
        styles = "".join(STYLE_LETTERS[s] for s in ("solid", "regular", "brands") if s in icon.get("styles", []))
        if not styles:
            continue
        words = list((icon.get("search") or {}).get("terms") or [])
        words += list((icon.get("aliases") or {}).get("names") or [])
        out.append([name, styles, icon.get("label") or name, " ".join(str(w) for w in words)])
    return out


def main(path):
    with open(path, encoding="utf-8") as f:
        icons = yaml.safe_load(f)
    data = entries(icons)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_fa_icons.py from Font Awesome Free 6.5.1 metadata. Do not edit by hand.\n")
        f.write("window.SceIcons = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print("wrote %d icons to %s" % (len(data), os.path.normpath(OUT)))


if __name__ == "__main__":
    main(sys.argv[1])
